"""
Self-contained, interactive visual HTML diagnostic report generator for skillpulse.
Generates an offline-ready single-file HTML dashboard with embedded Obsidian dark-mode styling,
interactive Skill <-> MCP Contract Topology Map, Model Context Budget Meter, and 1-click clipboard actions.
"""

import base64
import html
import json
from pathlib import Path
from typing import Union, List, Dict, Any
from skillpulse.models import ScanResult, SkillReport, MCPReport, DiagnosticIssue
from skillpulse.scorer import HealthScorer


class HTMLReporter:
    """Compiles a ScanResult into a polished standalone HTML dashboard."""

    @classmethod
    def generate(cls, scan_result: ScanResult, output_path: Union[str, Path] = "skillpulse-report.html") -> Path:
        output_file = Path(output_path).resolve()
        html_content = cls.build_html(scan_result)
        output_file.write_text(html_content, encoding="utf-8")
        return output_file

    @classmethod
    def build_markdown_summary(cls, scan: ScanResult) -> str:
        """Constructs an embeddable Markdown PR comment payload."""
        lines = []
        lines.append("## 🔍 SkillPulse Diagnostics & Health Summary")
        lines.append("")
        status_label = "✅ PASSED" if scan.total_errors == 0 else "❌ CRITICAL ERRORS DETECTED"
        lines.append(f"**Health Score:** `{scan.health_score}%` (**Grade {scan.grade}**) | **Status:** {status_label}")
        lines.append("")
        lines.append("| Metric | Value | Status |")
        lines.append("| :--- | :--- | :--- |")
        lines.append(f"| **Ecosystem Health** | `{scan.health_score}%` (Grade {scan.grade}) | {'🟢 Ready' if scan.health_score >= 80 else '🔴 Action Required'} |")
        lines.append(f"| **Agent Skills Scanned** | `{len(scan.skills)}` | 📦 Inspected |")
        total_tools = len(scan.mcp_report.tools) if scan.mcp_report else 0
        lines.append(f"| **MCP Tools Verified** | `{total_tools}` | ⚙️ Protocol 2025-11-25 |")
        lines.append(f"| **Critical Errors** | `{scan.total_errors}` | {'🟢 0 errors' if scan.total_errors == 0 else '🔴 Blocks CI'} |")
        lines.append(f"| **Warnings / Cues** | `{scan.total_warnings}` | {'🟢 Clean' if scan.total_warnings == 0 else '🟡 Review'} |")
        if scan.mcp_report:
            ghosts = len(scan.mcp_report.ghost_tools)
            orphans = len(scan.mcp_report.orphan_tools)
            stubs = len(scan.mcp_report.stub_tools)
            lines.append(f"| **Ghost Tools (MCP003)** | `{ghosts}` | {'🟢 None' if ghosts == 0 else '🔴 Undefined calls'} |")
            lines.append(f"| **Orphan Tools (MCP004)** | `{orphans}` | {'🟢 None' if orphans == 0 else '🟡 Unreferenced'} |")
            lines.append(f"| **Placeholder Stubs (MCP005)** | `{stubs}` | {'🟢 None' if stubs == 0 else '🟡 Unimplemented'} |")
        lines.append("")

        all_issues = []
        for skill in scan.skills:
            for iss in skill.issues:
                all_issues.append((skill.file_path, iss))
        if scan.mcp_report:
            for iss in scan.mcp_report.issues:
                all_issues.append((scan.mcp_report.source_file, iss))

        if all_issues:
            lines.append("### 📋 Diagnostic Findings")
            lines.append("")
            lines.append("| Severity | Rule | Location | Description | Remediation |")
            lines.append("| :--- | :--- | :--- | :--- | :--- |")
            for source, iss in all_issues:
                sev_badge = "🔴 ERROR" if iss.severity == "ERROR" else ("🟡 WARN" if iss.severity == "WARNING" else "🔵 INFO")
                loc = Path(source).name
                if iss.line_number:
                    loc += f":L{iss.line_number}"
                clean_msg = iss.message.replace("|", "\\|")
                clean_fix = iss.suggestion.replace("|", "\\|")
                lines.append(f"| {sev_badge} | `{iss.rule_id}` | `{loc}` | {clean_msg} | {clean_fix} |")
            lines.append("")
        else:
            lines.append("> ✅ **All Agent Skills and MCP tool schemas passed validation cleanly with zero errors.**")
            lines.append("")

        formula_str = HealthScorer.format_formula(scan.total_errors, scan.total_warnings, scan.health_score, scan.grade)
        lines.append(f"**Score Breakdown:** `{formula_str}`")
        lines.append("")
        lines.append("---")
        lines.append(f"*Generated by [SkillPulse](https://github.com/Zenfox-690/skillpulse) on `{scan.timestamp or 'Live Run'}`*")
        return "\n".join(lines)

    @classmethod
    def build_topology_map_html(cls, scan: ScanResult) -> str:
        """Renders interactive visual topology matrix between skills and MCP tools."""
        declared_tools = {t.name: t for t in (scan.mcp_report.tools if scan.mcp_report else [])}
        ghost_tools = set(scan.mcp_report.ghost_tools if scan.mcp_report else [])
        orphan_tools = set(scan.mcp_report.orphan_tools if scan.mcp_report else [])
        stub_tools = set(scan.mcp_report.stub_tools if scan.mcp_report else [])

        # Build contract rows
        contract_rows = []

        # 1. Links from skills to referenced tools
        for skill in scan.skills:
            if not skill.referenced_tools:
                contract_rows.append(f"""
                <div class="topo-link-row">
                  <div class="topo-node topo-skill">
                    <span class="topo-icon">📦</span>
                    <span class="topo-title">{html.escape(skill.name or 'Unnamed')}</span>
                  </div>
                  <div class="topo-connector connector-dim">
                    <span class="topo-badge badge-neutral">No Tools Required</span>
                  </div>
                  <div class="topo-node topo-empty">&mdash;</div>
                </div>
                """)
            else:
                for tool_name in skill.referenced_tools:
                    if tool_name in ghost_tools:
                        contract_rows.append(f"""
                        <div class="topo-link-row row-ghost">
                          <div class="topo-node topo-skill">
                            <span class="topo-icon">📦</span>
                            <span class="topo-title">{html.escape(skill.name)}</span>
                          </div>
                          <div class="topo-connector connector-ghost">
                            <span class="topo-badge badge-error pulse-danger">✖ Ghost Call (MCP003)</span>
                          </div>
                          <div class="topo-node topo-tool node-missing">
                            <span class="topo-icon">⚠️</span>
                            <span class="topo-title">{html.escape(tool_name)}</span>
                            <span class="topo-sub">Missing in MCP</span>
                          </div>
                        </div>
                        """)
                    elif tool_name in stub_tools or (tool_name in declared_tools and getattr(declared_tools[tool_name], "is_stub", False)):
                        contract_rows.append(f"""
                        <div class="topo-link-row row-stub">
                          <div class="topo-node topo-skill">
                            <span class="topo-icon">📦</span>
                            <span class="topo-title">{html.escape(skill.name)}</span>
                          </div>
                          <div class="topo-connector connector-stub">
                            <span class="topo-badge badge-warning">⚠ Schema Stub (Unimplemented)</span>
                          </div>
                          <div class="topo-node topo-tool node-stub">
                            <span class="topo-icon">⚠️</span>
                            <span class="topo-title">{html.escape(tool_name)}</span>
                            <span class="topo-sub">Unimplemented Stub (MCP005)</span>
                          </div>
                        </div>
                        """)
                    else:
                        contract_rows.append(f"""
                        <div class="topo-link-row row-active">
                          <div class="topo-node topo-skill">
                            <span class="topo-icon">📦</span>
                            <span class="topo-title">{html.escape(skill.name)}</span>
                          </div>
                          <div class="topo-connector connector-active">
                            <span class="topo-badge badge-pass">&#10003; Verified Contract</span>
                          </div>
                          <div class="topo-node topo-tool node-declared">
                            <span class="topo-icon">⚙️</span>
                            <span class="topo-title">{html.escape(tool_name)}</span>
                            <span class="topo-sub">MCP 2025-11-25</span>
                          </div>
                        </div>
                        """)

        # 2. Add orphan tools
        for orphan in sorted(list(orphan_tools)):
            contract_rows.append(f"""
            <div class="topo-link-row row-orphan">
              <div class="topo-node topo-empty">&mdash;</div>
              <div class="topo-connector connector-orphan">
                <span class="topo-badge badge-warning">? Orphan Tool (MCP004)</span>
              </div>
              <div class="topo-node topo-tool node-orphan">
                <span class="topo-icon">📦</span>
                <span class="topo-title">{html.escape(orphan)}</span>
                <span class="topo-sub">0 skills invoking</span>
              </div>
            </div>
            """)

        rows_html = "".join(contract_rows) if contract_rows else '<div class="empty-state">No active contracts detected.</div>'

        return f"""
        <div class="card topo-card">
          <div class="card-header">
            <div>
              <h3 class="card-title">🌐 Skill &amp; MCP Contract Topology Map</h3>
              <div class="file-path">Interactive visual contract graph mapping Agent Skill prompt instructions to Model Context Protocol declarations</div>
            </div>
            <div class="topo-legend">
              <span class="legend-item"><span class="dot dot-pass"></span> Verified Contract</span>
              <span class="legend-item"><span class="dot dot-stub"></span> Schema Stub (Unimplemented)</span>
              <span class="legend-item"><span class="dot dot-error"></span> Ghost Tool (MCP003)</span>
              <span class="legend-item"><span class="dot dot-warn"></span> Orphan Tool (MCP004)</span>
            </div>
          </div>
          <div class="topo-matrix">
            <div class="topo-matrix-header">
              <div class="col-head">Agent Skills (`SKILL.md`)</div>
              <div class="col-head text-center">Protocol Interface &amp; Contract State</div>
              <div class="col-head text-right">Declared MCP Tools (`2025-11-25`)</div>
            </div>
            <div class="topo-matrix-body">
              {rows_html}
            </div>
          </div>
        </div>
        """

